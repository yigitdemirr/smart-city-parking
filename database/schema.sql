-- =====================================================================
-- Smart City Parking System (Project B) - PostgreSQL 16 schema
-- Milestone M1: conceptual design, implemented as executable DDL.
-- Run:  psql -d parking -f database/schema.sql
-- =====================================================================

-- btree_gist lets one exclusion constraint combine "same space" (=)
-- with "overlapping time period" (&&). It is the database-level guard
-- against two active reservations for one space at the same time.
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- gen_random_uuid()

-- ---------------------------------------------------------------------
-- USERS: drivers and administrators
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id             UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,              -- bcrypt/argon2, never plain text
    display_name   VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL DEFAULT 'DRIVER'
                   CHECK (role IN ('DRIVER', 'ADMIN')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

-- ---------------------------------------------------------------------
-- PARKING_FACILITIES: a car park / street zone with one location
-- Origin of location data: entered by an administrator (or seed data
-- for the simulated city). Coordinates are WGS-84 decimal degrees.
-- ---------------------------------------------------------------------
CREATE TABLE parking_facilities (
    id            UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    name          VARCHAR(120)  NOT NULL,
    address       VARCHAR(255)  NOT NULL,
    latitude      NUMERIC(9,6)  NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude     NUMERIC(9,6)  NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    data_source   VARCHAR(20)   NOT NULL DEFAULT 'ADMIN_ENTRY'
                  CHECK (data_source IN ('ADMIN_ENTRY', 'SEED_SIMULATED')),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_facilities_lat_lon ON parking_facilities (latitude, longitude);

-- ---------------------------------------------------------------------
-- PARKING_SPACES: one bookable space inside a facility
-- ---------------------------------------------------------------------
CREATE TABLE parking_spaces (
    id              UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    facility_id     UUID          NOT NULL REFERENCES parking_facilities(id),
    label           VARCHAR(20)   NOT NULL,              -- e.g. "A-12"
    space_type      VARCHAR(12)   NOT NULL DEFAULT 'STANDARD'
                    CHECK (space_type IN ('STANDARD', 'DISABLED', 'EV')),
    price_per_hour  NUMERIC(8,2)  NOT NULL CHECK (price_per_hour >= 0),   -- PLN
    is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
    version         INTEGER       NOT NULL DEFAULT 1,    -- optimistic locking for admin edits
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ux_space_label_per_facility UNIQUE (facility_id, label)
);

-- ---------------------------------------------------------------------
-- OPERATIONS: stable operation identity for every data-changing request.
-- The client generates operation_id (UUID v4) once per user intent and
-- re-sends the same value on every retry. The row is written in the SAME
-- transaction as the business change, so "operation recorded" and
-- "change applied" can never disagree.
-- ---------------------------------------------------------------------
CREATE TABLE operations (
    operation_id    UUID          PRIMARY KEY,           -- generated by the client
    user_id         UUID          NOT NULL REFERENCES users(id),
    operation_type  VARCHAR(30)   NOT NULL
                    CHECK (operation_type IN ('HOLD_SPACE', 'PAY_RESERVATION',
                                              'CANCEL_RESERVATION', 'ADMIN_UPSERT_SPACE')),
    request_hash    CHAR(64)      NOT NULL,              -- SHA-256 of canonical request body
    outcome         VARCHAR(10)   NOT NULL CHECK (outcome IN ('SUCCEEDED', 'REJECTED')),
    http_status     SMALLINT      NOT NULL,
    response_body   JSONB         NOT NULL,              -- replayed verbatim on retry
    resource_type   VARCHAR(20),
    resource_id     UUID,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_operations_user ON operations (user_id, created_at DESC);

-- ---------------------------------------------------------------------
-- RESERVATIONS: HELD (temporary block) -> CONFIRMED (paid) or
--               HELD -> EXPIRED / CANCELLED, CONFIRMED -> CANCELLED / COMPLETED
-- ---------------------------------------------------------------------
CREATE TABLE reservations (
    id                     UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                UUID          NOT NULL REFERENCES users(id),
    space_id               UUID          NOT NULL REFERENCES parking_spaces(id),
    operation_id           UUID          NOT NULL UNIQUE REFERENCES operations(operation_id)
                                         DEFERRABLE INITIALLY DEFERRED,
    status                 VARCHAR(10)   NOT NULL DEFAULT 'HELD'
                           CHECK (status IN ('HELD', 'CONFIRMED', 'EXPIRED',
                                             'CANCELLED', 'COMPLETED')),
    start_time             TIMESTAMPTZ   NOT NULL,
    end_time               TIMESTAMPTZ   NOT NULL,
    period                 TSTZRANGE     GENERATED ALWAYS AS
                                         (tstzrange(start_time, end_time, '[)')) STORED,
    hold_expires_at        TIMESTAMPTZ   NOT NULL,       -- created_at + 10 min
    price_per_hour_snapshot NUMERIC(8,2) NOT NULL,       -- price at the moment of the hold
    total_amount           NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version                INTEGER       NOT NULL DEFAULT 1,
    CONSTRAINT ck_reservation_period CHECK (end_time > start_time
                                            AND end_time - start_time <= INTERVAL '24 hours'),
    -- Competing requests: at most ONE active (HELD/CONFIRMED) reservation
    -- may overlap in time on the same space. The loser gets SPACE_UNAVAILABLE.
    CONSTRAINT ex_no_double_booking EXCLUDE USING gist
        (space_id WITH =, period WITH &&)
        WHERE (status IN ('HELD', 'CONFIRMED'))
);
CREATE INDEX ix_reservations_user   ON reservations (user_id, created_at DESC);
CREATE INDEX ix_reservations_expiry ON reservations (hold_expires_at) WHERE status = 'HELD';

-- ---------------------------------------------------------------------
-- PAYMENTS: SIMULATED only - no real money, no card data stored.
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id              UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    reservation_id  UUID          NOT NULL REFERENCES reservations(id),
    operation_id    UUID          NOT NULL UNIQUE REFERENCES operations(operation_id)
                                  DEFERRABLE INITIALLY DEFERRED,
    amount          NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    currency        CHAR(3)       NOT NULL DEFAULT 'PLN',
    method          VARCHAR(20)   NOT NULL DEFAULT 'SIMULATED_CARD',
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('SUCCEEDED', 'DECLINED')),
    is_simulated    BOOLEAN       NOT NULL DEFAULT TRUE CHECK (is_simulated),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- A reservation can have several declined attempts but only one success.
CREATE UNIQUE INDEX ux_one_successful_payment
    ON payments (reservation_id) WHERE status = 'SUCCEEDED';
